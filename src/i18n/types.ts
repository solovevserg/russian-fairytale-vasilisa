/** Глава сказки: id (общий для всех языков, по нему — кадр сцены) и текст. */
export interface Chapter {
	/** Идентификатор главы — одинаковый во всех языках, по нему выбирается кадр сцены. */
	id: string;
	/** Название главы. */
	title: string;
	/** Абзацы текста по порядку. */
	paragraphs: string[];
}

/**
 * Файл перевода `src/i18n/locales/<язык>.json` — все тексты сказки и
 * интерфейса на одном языке. Каждый JSON проверяется на соответствие этому
 * интерфейсу при компиляции (см. LOCALES в content.ts), а одинаковый набор
 * ключей и глав во всех языках — юнит-тестом (tests/unit/i18n.test.ts).
 */
export interface Locale {
	/** Название сказки — на титульной карточке. */
	title: string;
	/** Подзаголовок: «Русская народная сказка». */
	subtitle: string;
	/** Откуда текст: «по мотивам собрания А. Н. Афанасьева». */
	source: string;
	/** Заголовок вкладки браузера. */
	documentTitle: string;
	/** meta description для поисковиков и превью ссылок. */
	description: string;
	/** Язык синтеза речи для озвучки (BCP 47, например `ru-RU`). */
	speechLang: string;
	/** Подписи над названиями глав: «Зачин», «Глава первая»…, «Концовка». */
	captions: {
		/** Подпись первой главы (пролога). */
		beginning: string;
		/** Подпись последней главы (эпилога). */
		ending: string;
		/** Подпись остальных глав; `{ordinal}` заменяется порядковым числительным. */
		chapter: string;
		/** Порядковые числительные: первая, вторая… (для глав со второй по предпоследнюю). */
		ordinals: string[];
	};
	/** Строки интерфейса. */
	ui: {
		/** Кнопка автопрокрутки. */
		read: string;
		/** Короткая подпись кнопки автопрокрутки для мобильных. */
		readShort: string;
		/** Кнопка паузы автопрокрутки. */
		pause: string;
		/** Переключатель озвучки. */
		narrate: string;
		/** Переключатель озвучки во включённом состоянии. */
		narrateOn: string;
		/** Всплывающая подсказка переключателя озвучки. */
		narrateTitle: string;
		/** Кнопка звука: звук включён. */
		soundOn: string;
		/** Кнопка звука: звук выключен. */
		soundOff: string;
		/** Подпись для скринридеров: включить звук. */
		soundEnable: string;
		/** Подпись для скринридеров: выключить звук. */
		soundDisable: string;
		/** Переключатель на светлую тему. */
		themeLight: string;
		/** Переключатель на тёмную тему. */
		themeDark: string;
		/** Подсказка на первом экране мобильной версии: [как листать, что «Читать» — само]. */
		swipeHint: string[];
		/** Кнопка на финальной карточке (телефон): вернуться к началу сказки. */
		backToStart: string;
		/** Подпись меню языков. */
		language: string;
		/** Подпись панели управления для скринридеров. */
		toolbar: string;
		/** Подпись навигации по главам. */
		chaptersNav: string;
		/** Кнопка «предыдущая глава». */
		prevChapter: string;
		/** Кнопка «следующая глава». */
		nextChapter: string;
		/** Титры на финальной карточке. */
		credits: {
			/** Музыка, звуки, текстуры, шрифты и их лицензии. */
			music: string;
			/** Вступление к списку 3D-моделей. */
			models: string;
			/** Надзаголовок титров. */
			authorRole: string;
			/** Имя автора — заголовок титров. */
			authorName: string;
			/** Посвящение — под именем автора. */
			dedication: string;
			/** Текст вокруг ссылки на Claude: [до ссылки, после ссылки]. */
			withClaude: string[];
			/** Ссылка на полный список источников. */
			allSources: string;
			/** Ссылка на исходный код. */
			sourceCode: string;
		};
	};
	/** Главы по порядку; id и порядок одинаковы во всех языках. */
	chapters: Chapter[];
}
